#!/usr/bin/env python
"""THE figure generator. Every PNG in ``docs/images/`` comes from this file.

Nothing in this repo is hand-exported: if a figure cannot be regenerated by one command it
does not ship. ``make figures`` runs this against the explicit published run.

Eleven figures:

===============================  ============================================================
``confusion_matrix_baseline``    TF-IDF + LogReg, counts and row-normalised side by side
``confusion_matrix_roberta``     fine-tuned RoBERTa, same layout
``training_curves``              per-epoch train and **validation** loss (justifies D4)
``attention_heatmap``            last-layer head-mean attention, inner tokens only
``attention_from_token``         what one chosen source token attends to
``saliency_positive``            gradient-norm saliency, 3 positive reviews, post-D1-fix
``saliency_negative``            gradient-norm saliency, 3 negative reviews, post-D1-fix
``baseline_ablation``            the 2x2 preprocessing grid
``embedding_space_3d``           final-layer [CLS] under t-SNE, errors marked
``layer_probe_accuracy``         linear-probe accuracy against hidden-state index
``attention_entropy_atlas``      mean entropy of all 12x12 heads over the test set
===============================  ============================================================

Every caption names the model and the config that produced it, because a figure whose
provenance is unstated is indistinguishable from a figure taken from somewhere else.

The default publication path regenerates every figure from committed review-text-free evidence.
``--write-model-evidence`` performs forward passes on an existing checkpoint and records the
lower-level arrays; it never refits the transformer. Pass ``--skip-model-figures`` to produce only
the metric figures.

``layer_probe_accuracy`` additionally needs the run's TRAIN rows, which live in the source
parquet rather than in the run directory: a probe fitted on the same rows it is scored on
would measure memorisation. The split is rebuilt from the run's own config and seed, and the
rebuilt test split is asserted identical to ``predictions.parquet`` before anything is fitted.

Usage
-----
    uv run python scripts/export_figures.py -i runs/run_2 -a runs/run_3 -o docs/images
"""

