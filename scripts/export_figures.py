def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _fig_confusion(matrix: np.ndarray, title: str, caption_text: str) -> Any:
    import matplotlib.pyplot as plt

    counts = np.asarray(matrix, dtype=float)
    with np.errstate(invalid="ignore", divide="ignore"):
        normed = counts / counts.sum(axis=1, keepdims=True)
    normed = np.nan_to_num(normed)

    fig, axes = plt.subplots(1, 2, figsize=(8.4, 3.7))
    for ax, data, fmt, sub, vmax in (
        (axes[0], counts, "{:.0f}", "counts", counts.max()),
        (axes[1], normed, "{:.3f}", "row-normalised (recall)", 1.0),
    ):
        im = ax.imshow(data, cmap="Blues", vmin=0, vmax=vmax)
        ax.set_xticks([0, 1], labels=[f"pred {c}" for c in CLASS_LABELS])
        ax.set_yticks([0, 1], labels=[f"true {c}" for c in CLASS_LABELS])
        ax.set_title(sub, fontsize=10, fontweight="normal")
        ax.grid(visible=False)
        for i in range(2):
            for j in range(2):
                shade = data[i, j] / (vmax if vmax else 1)
                ax.text(
                    j,
                    i,
                    fmt.format(data[i, j]),
                    ha="center",
                    va="center",
                    fontsize=11,
                    color="white" if shade > 0.55 else "#111111",
                )
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.suptitle(title, fontsize=12, fontweight="bold")
    plots.caption(axes[0], caption_text)
    fig.tight_layout()
    return fig


def figure_confusion_matrices(metrics: dict[str, Any], out_dirs: list[Path]) -> list[Path]:
    written: list[Path] = []
    cfg_name = metrics["config_name"]
    pretty = {
        "tfidf_logreg": "TF-IDF + Logistic Regression (control)",
        "roberta": "RoBERTa (fine-tuned)",
    }
    filename = {"tfidf_logreg": "confusion_matrix_baseline", "roberta": "confusion_matrix_roberta"}
    for key, block in metrics["models"].items():
        if key not in filename:
            continue
        acc = block["accuracy"]
        ci = block["accuracy_ci"]
        fig = _fig_confusion(
            np.asarray(block["confusion_matrix"]),
            pretty[key],
            f"{pretty[key]} · cfg/{cfg_name}.yaml · n_test={block['n_test']} · "
            f"accuracy {acc:.4f} (Wilson 95% CI {ci['low']:.4f}-{ci['high']:.4f}) · "
            f"seed {metrics['seed']} · {metrics['device']}",
        )
        plots.set_provenance(
            fig,
            {
                "accuracy": acc,
                "accuracy_ci": ci,
                "config_name": cfg_name,
                "confusion_matrix": block["confusion_matrix"],
                "model": key,
                "n_test": block["n_test"],
                "seed": metrics["seed"],
            },
        )
        written += plots.save_figure(fig, filename[key], out_dirs)
    return written


def figure_training_curves(metrics: dict[str, Any], out_dirs: list[Path]) -> list[Path]:
    import matplotlib.pyplot as plt

    block = metrics["models"].get("roberta")
    if not block:
        return []
    history = block["training"]["history"]
    if not history:
        return []

    epochs = [h["epoch"] for h in history]
    train = [h["train_loss"] for h in history]
    val = [h["val_loss"] for h in history]
    val_acc = [h["val_accuracy"] for h in history]
    epoch_ticks = [int(epoch) for epoch in epochs]

    fig, (ax, ax2) = plt.subplots(
        2,
        1,
        figsize=(9.0, 5.8),
        sharex=True,
        gridspec_kw={"height_ratios": [2.35, 1.0]},
    )
    ax.plot(
        epochs,
        train,
        marker="o",
        markersize=5.5,
        linestyle="-",
        linewidth=1.8,
        label="training loss",
        color=plots.OKABE_ITO[0],
    )
    ax.plot(
        epochs,
        val,
        marker="s",
        markersize=5.5,
        linestyle="--",
        linewidth=1.8,
        label="validation loss",
        color=plots.OKABE_ITO[1],
    )
    selected = block["training"]["selected_epoch"]
    ax.axvline(selected, linestyle="-.", linewidth=1.2, color="#555555")
    ax2.axvline(selected, linestyle="-.", linewidth=1.2, color="#555555")
    criterion = block["training"]["selection_criterion"]
    criterion_label = "lowest validation loss" if criterion == "min validation loss" else criterion
    ax.text(
        selected + 0.06,
        0.08,
        f"selected: {criterion_label}",
        transform=ax.get_xaxis_transform(),
        fontsize=8,
        color="#333333",
        ha="left",
        va="center",
        bbox={"facecolor": "white", "edgecolor": "none", "alpha": 0.88, "pad": 1.5},
    )
    ax.set_ylabel("loss (cross entropy)")
    ax.legend(loc="upper right")

    ax2.plot(
        epochs,
        val_acc,
        marker="^",
        markersize=5.0,
        linestyle=":",
        linewidth=1.5,
        color=plots.OKABE_ITO[2],
    )
    ax2.set_xlabel("training epoch")
    ax2.set_ylabel("validation accuracy")
    ax2.set_xticks(epoch_ticks)

    run = block["training"]
    fig.suptitle("Validation loss rose after epoch 1", fontsize=13, fontweight="bold")
    plots.caption(
        ax,
        f"cfg/{metrics['config_name']}.yaml · {block['n_train']} train / {block['n_val']} val · "
        f"seed {metrics['seed']} · {metrics['device']}, {metrics['power_mode']} · "
        f"epochs run {run['epochs_run']}/{run['epochs_configured']}"
        + (" · WALL-CLOCK CAPPED" if run["wall_clock_capped"] else "")
        + f" · epoch selected on {run['selection_criterion']}",
    )
    plots.set_provenance(
        fig,
        {
            "config_name": metrics["config_name"],
            "history": history,
            "model": "roberta",
            "seed": metrics["seed"],
            "selected_epoch": selected,
        },
    )
    fig.tight_layout(rect=(0, 0.03, 1, 0.96), h_pad=1.0)
    with plt.rc_context({"savefig.dpi": 160}):
        return plots.save_figure(fig, "training_curves", out_dirs)


def figure_baseline_ablation(
    metrics: dict[str, Any], out_dirs: list[Path], ablation_metrics: dict[str, Any] | None = None
) -> list[Path]:
    import matplotlib.pyplot as plt

    source = ablation_metrics or metrics
    cells = source.get("ablation") or []
    if not cells:
        return []

    labels = [c["ablation_label"] for c in cells]
    accs = [c["accuracy"] for c in cells]
    lows = [c["accuracy_ci"]["low"] for c in cells]
    highs = [c["accuracy_ci"]["high"] for c in cells]
    errs = np.array(
        [
            [a - lo for a, lo in zip(accs, lows, strict=True)],
            [hi - a for a, hi in zip(accs, highs, strict=True)],
        ]
    )
    colors = [plots.OKABE_ITO[1] if "notebook" in label else plots.OKABE_ITO[0] for label in labels]

    fig, ax = plt.subplots(figsize=(8.6, 3.9))
    y = np.arange(len(labels))
    ax.barh(
        y,
        accs,
        xerr=errs,
        color=colors,
        height=0.62,
        error_kw={"ecolor": "#444444", "capsize": 3, "lw": 1},
    )
    ax.set_yticks(y, labels=labels)
    ax.invert_yaxis()
    ax.set_xlabel("test accuracy (Wilson 95% CI)")
    roberta = metrics["models"].get("roberta")
    show_roberta = bool(roberta) and not roberta.get("random_weights", False)
    # The transformer reference line is the point of comparison, so the x-range has to
    # include it. Otherwise the axvline is drawn off-chart and silently disappears.
    right = max(highs) + 0.035
    if show_roberta:
        right = max(right, roberta["accuracy"] + 0.02)
    ax.set_xlim(max(0.0, min(lows) - 0.02), min(1.0, right))
    ax.grid(visible=True, axis="x", alpha=0.25)
    ax.grid(visible=False, axis="y")
    # Anchor the value label past the upper whisker, not at the bar end. The bar end is exactly
    # where the error bar is centred, so a label placed there covers its own whisker.
    for yi, a, high in zip(y, accs, highs, strict=True):
        ax.annotate(
            f"{a:.4f}",
            xy=(high, float(yi)),
            xytext=(5, 0),
            textcoords="offset points",
            ha="left",
            va="center",
            fontsize=9,
        )

    if show_roberta:
        ax.axvline(roberta["accuracy"], ls="--", lw=1.4, color="#111111")
        ax.annotate(
            f"fine-tuned RoBERTa\n{roberta['accuracy']:.4f}",
            xy=(roberta["accuracy"], 0.0),
            xytext=(-6, 0),
            textcoords="offset points",
            fontsize=8,
            ha="right",
            va="center",
            color="#111111",
        )

    ax.set_title("TF-IDF control: what conventional preprocessing costs")
    plots.caption(
        ax,
        f"TF-IDF + LogReg · cfg/{source['config_name']}.yaml · "
        f"n_train={cells[0]['n_train']} / n_test={cells[0]['n_test']} · seed {source['seed']} · "
        "orange = the source notebook's chain (alphanumeric-only filter + NLTK stopword removal "
        "+ Porter stemming), which deletes not/no/nor and every contraction",
    )
    plots.set_provenance(
        fig,
        {
            "ablation": [
                {
                    "accuracy": cell["accuracy"],
                    "accuracy_ci": cell["accuracy_ci"],
                    "label": cell["ablation_label"],
                }
                for cell in cells
            ],
            "config_name": source["config_name"],
            "roberta_accuracy": roberta["accuracy"] if show_roberta else None,
            "seed": source["seed"],
        },
    )
    fig.tight_layout()
    return plots.save_figure(fig, "baseline_ablation", out_dirs)


