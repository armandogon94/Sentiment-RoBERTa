def figure_attention(
    model: Any, cfg: Any, device: Any, text: str, metrics: dict[str, Any], out_dirs: list[Path]
) -> list[Path]:
    import matplotlib.pyplot as plt

    from interpretability.attention import last_layer_attention, pick_source_token

    amap = last_layer_attention(
        model.model, model.tokenizer, text, max_len=cfg.MODEL.MAX_LEN, device=device
    )
    # Keep the heatmap legible: the first 32 inner tokens, which is where the signal is.
    k = min(32, len(amap.tokens))
    tokens = [t.lstrip("Ġ") for t in amap.tokens[:k]]
    matrix = amap.matrix[:k, :k]

    fig, ax = plt.subplots(figsize=(8.6, 7.2))
    im = ax.imshow(matrix, cmap="magma", aspect="auto")
    ax.set_xticks(range(k), labels=tokens, rotation=90, fontsize=7)
    ax.set_yticks(range(k), labels=tokens, fontsize=7)
    ax.set_xlabel("attended-to token (key)")
    ax.set_ylabel("attending token (query)")
    ax.grid(visible=False)
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.03, label="attention weight")
    ax.set_title(f"Last-layer attention (layer {amap.layer}, mean over {amap.n_heads} heads)")
    plots.caption(
        ax,
        f"RoBERTa fine-tuned, cfg/{metrics['config_name']}.yaml · first {k} inner tokens "
        f"(<s>/</s>/<pad> excluded, since <s> is an attention sink and flattens the colour scale) · "
        f"predicted {CLASS_LABELS[amap.predicted_label]} · eager attention (sdpa returns no "
        "attentions at all on transformers 5.x) · attention is not causal explanation",
    )
    shared_provenance = {
        "checkpoint_sha256": metrics["_checkpoint_sha256"],
        "config_name": metrics["config_name"],
        "method": "last_layer_head_mean_attention",
        "model": "roberta",
        "run_git_sha": metrics["git_sha"],
        "seed": metrics["seed"],
        "source_row_position": NOTEBOOK_REVIEW_POSITIONS[0],
    }
    plots.set_provenance(fig, shared_provenance)
    fig.tight_layout()
    written = plots.save_figure(fig, "attention_heatmap", out_dirs)

    idx = pick_source_token(amap, preferred=("not", "great", "bad", "good", "no"))
    row = amap.row_for(idx)
    order = np.argsort(-row)[: min(15, row.size)]
    fig2, ax2 = plt.subplots(figsize=(8.6, 3.6))
    ax2.bar(
        range(len(order)),
        row[order],
        color=plots.OKABE_ITO[0],
    )
    ax2.set_xticks(
        range(len(order)),
        labels=[amap.tokens[i].lstrip("Ġ") for i in order],
        rotation=60,
        ha="right",
    )
    ax2.set_ylabel("attention weight")
    ax2.set_xlabel("attended-to token")
    ax2.set_title(f"What '{amap.tokens[idx].lstrip('Ġ')}' attends to (top {len(order)})")
    plots.caption(
        ax2,
        f"RoBERTa fine-tuned, cfg/{metrics['config_name']}.yaml · source token "
        f"'{amap.tokens[idx].lstrip('Ġ')}' · last layer, head-mean · same review as the heatmap",
    )
    plots.set_provenance(fig2, shared_provenance)
    fig2.tight_layout()
    written += plots.save_figure(fig2, "attention_from_token", out_dirs)
    return written


def figure_saliency(
    model: Any,
    cfg: Any,
    device: Any,
    examples: list[tuple[str, int]],
    label_name: str,
    metrics: dict[str, Any],
    out_dirs: list[Path],
) -> list[Path]:
    import matplotlib.pyplot as plt

    from interpretability.saliency import gradient_saliency

    n = len(examples)
    fig, axes = plt.subplots(n, 1, figsize=(9.0, 2.5 * n))
    axes_list = list(np.atleast_1d(axes))
    for ax, (text, true_label) in zip(axes_list, examples, strict=True):
        attr = gradient_saliency(
            model.model, model.tokenizer, text, max_len=cfg.MODEL.MAX_LEN, device=device
        )
        keep = [i for i, t in enumerate(attr.tokens) if t not in {"<s>", "</s>", "<pad>"}]
        keep = keep[: min(26, len(keep))]
        toks = [attr.tokens[i].lstrip("Ġ") for i in keep]
        vals = attr.scores[keep]
        ax.bar(
            range(len(toks)),
            vals,
            color=plots.POSITIVE_COLOR if attr.predicted_label == 1 else plots.NEGATIVE_COLOR,
        )
        ax.set_xticks(range(len(toks)), labels=toks, rotation=60, ha="right", fontsize=7)
        # Short enough to stay inside its own panel: a longer label is centred over a 2.5in
        # axis and runs into the rotated tick labels of the panel above it. The quantity is
        # named in full in the figure title and the caption.
        ax.set_ylabel("Token importance", fontsize=9)
        ax.set_title(
            f"true {CLASS_LABELS[true_label]} · predicted {CLASS_LABELS[attr.predicted_label]}"
            f"{'' if attr.predicted_label == true_label else '  ← MISCLASSIFIED'}",
            fontsize=10,
            fontweight="normal",
        )
    fig.suptitle(f"Gradient-norm saliency: {label_name} reviews", fontsize=12, fontweight="bold")
    plots.caption(
        axes_list[-1],
        f"RoBERTa fine-tuned, cfg/{metrics['config_name']}.yaml · gradient of the predicted-class "
        "logit w.r.t. the WORD embeddings only (the D1 fix: the notebook re-applied the full "
        "embedding module, adding position/token-type/LayerNorm twice) · this is gradient-norm "
        "saliency, NOT Grad-CAM, and it satisfies none of Integrated Gradients' axioms",
    )
    plots.set_provenance(
        fig,
        {
            "checkpoint_sha256": metrics["_checkpoint_sha256"],
            "config_name": metrics["config_name"],
            "example_count": len(examples),
            "label": label_name,
            "method": "gradient_norm_saliency",
            "model": "roberta",
            "run_git_sha": metrics["git_sha"],
            "seed": metrics["seed"],
        },
    )
    fig.tight_layout()
    fig.subplots_adjust(hspace=0.75)
    slug = "saliency_positive" if label_name == "positive" else "saliency_negative"
    return plots.save_figure(fig, slug, out_dirs)


def _preflight(
    run_dir: Path,
    metrics: dict[str, Any],
    ablation_run_dir: Path | None,
    *,
    skip_model_figures: bool,
) -> dict[str, Any] | None:
    """Validate every required input before the first PNG can be written."""
    if skip_model_figures:
        return (
            read_json(ablation_run_dir / "metrics.json") if ablation_run_dir is not None else None
        )

    for required in ("model_roberta.pt", "predictions.parquet"):
        path = run_dir / required
        if not path.is_file():
            raise FileNotFoundError(
                f"{path} not found; a complete eight-figure export requires the published "
                "checkpoint and paired predictions"
            )
    roberta = metrics.get("models", {}).get("roberta")
    if not roberta or not roberta.get("training", {}).get("history"):
        raise ValueError(
            f"{run_dir / 'metrics.json'} has no fine-tuned RoBERTa training history; "
            "refusing to produce a partial publication set"
        )
    if ablation_run_dir is None:
        raise ValueError(
            "a complete eight-figure export requires --ablation-run-dir "
            "(the published target uses runs/run_3)"
        )
    ablation_path = ablation_run_dir / "metrics.json"
    if not ablation_path.is_file():
        raise FileNotFoundError(
            f"{ablation_path} not found; the baseline ablation figure cannot be generated"
        )
    ablation_metrics = read_json(ablation_path)
    if len(ablation_metrics.get("ablation") or []) != 4:
        raise ValueError(
            f"{ablation_path} does not contain the required four-cell ablation; "
            "refusing to produce a partial publication set"
        )
    return ablation_metrics


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("-i", "--run-dir", type=Path, default=REPO_ROOT / "runs" / "latest")
    ap.add_argument("-o", "--out-dir", type=Path, default=REPO_ROOT / "docs" / "images")
    ap.add_argument(
        "-a",
        "--ablation-run-dir",
        type=Path,
        default=None,
        help="run dir holding the ablation cells, if a different run produced them",
    )
    ap.add_argument("--skip-model-figures", action="store_true", help="metric figures only")
    ap.add_argument(
        "--publish",
        action="store_true",
        help="also mirror the requested output into tracked reports/figures (explicit opt-in)",
    )
    ap.add_argument("--show", action="store_true", help="also display interactively (never in CI)")
    args = ap.parse_args(argv)

    run_dir = args.run_dir.resolve()
    metrics = read_json(run_dir / "metrics.json")
    ablation_run_dir = args.ablation_run_dir.resolve() if args.ablation_run_dir else None
    ablation_metrics = _preflight(
        run_dir,
        metrics,
        ablation_run_dir,
        skip_model_figures=args.skip_model_figures,
    )
    out_dirs = [args.out_dir.resolve()]
    if args.publish:
        publication_dir = (REPO_ROOT / "reports" / "figures").resolve()
        if publication_dir not in out_dirs:
            out_dirs.append(publication_dir)

    plots.apply_style()
    if args.show:  # pragma: no cover - interactive only
        plots.enable_interactive()

    written: list[Path] = []
    written += figure_confusion_matrices(metrics, out_dirs)
    written += figure_training_curves(metrics, out_dirs)
    written += figure_baseline_ablation(metrics, out_dirs, ablation_metrics)

    if not args.skip_model_figures:
        model, cfg, device = _load_model_for_figures(run_dir, metrics)
        model_metrics = {
            **metrics,
            "_checkpoint_sha256": _sha256(run_dir / "model_roberta.pt"),
        }
        frame = _example_texts(run_dir)
        positions = [p for p in NOTEBOOK_REVIEW_POSITIONS if p < len(frame)]
        rows = [(str(frame["text"].iloc[p]), int(frame["label"].iloc[p])) for p in positions]
        positives = [r for r in rows if r[1] == 1][:3]
        negatives = [r for r in rows if r[1] == 0][:3]
        # Backfill from the split if the notebook's six positions are lopsided in this run.
        for want, bucket in ((1, positives), (0, negatives)):
            i = 0
            while len(bucket) < 3 and i < len(frame):
                if int(frame["label"].iloc[i]) == want:
                    candidate = (str(frame["text"].iloc[i]), want)
                    if candidate not in bucket:
                        bucket.append(candidate)
                i += 1

        written += figure_attention(model, cfg, device, rows[0][0], model_metrics, out_dirs)
        written += figure_saliency(
            model, cfg, device, positives, "positive", model_metrics, out_dirs
        )
        written += figure_saliency(
            model, cfg, device, negatives, "negative", model_metrics, out_dirs
        )

    unique_names = sorted({p.name for p in written})
    if not args.skip_model_figures and set(unique_names) != EXPECTED_FIGURES:
        missing = sorted(EXPECTED_FIGURES - set(unique_names))
        extra = sorted(set(unique_names) - EXPECTED_FIGURES)
        raise RuntimeError(
            f"figure export was incomplete: missing={missing or 'none'}, extra={extra or 'none'}"
        )
    print(f"==> wrote {len(unique_names)} distinct figures into {len(out_dirs)} directories")
    for name in unique_names:
        print(f"    {name}")
    return 0


