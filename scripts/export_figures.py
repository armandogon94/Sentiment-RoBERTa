def figure_representations(
    model: Any,
    cfg: Any,
    device: Any,
    run_dir: Path,
    metrics: dict[str, Any],
    out_dirs: list[Path],
) -> list[Path]:
    """Figures 9, 10 and 11, which share one pass over the test split."""
    from datasets.splits import combined_text
    from interpretability.representations import (
        attention_entropy_atlas,
        boundary_summary,
        cls_representations,
        layer_probe_curve,
        saturation_layer,
    )

    splits = _rebuilt_splits(cfg, run_dir)
    test_texts = [str(t) for t in combined_text(splits.test)]
    train_texts = [str(t) for t in combined_text(splits.train)]
    y_test = np.asarray([int(v) for v in splits.test["label"]], dtype=np.int64)
    y_train = [int(v) for v in splits.train["label"]]

    test_reps = cls_representations(
        model.model,
        model.tokenizer,
        test_texts,
        max_len=cfg.MODEL.MAX_LEN,
        device=device,
        batch_size=cfg.MODEL.BATCH_SIZE,
    )
    summary = boundary_summary(test_reps, y_test, n_neighbours=BOUNDARY_NEIGHBOURS)
    written = figure_embedding_space(test_reps, y_test, summary, metrics, out_dirs)

    train_reps = cls_representations(
        model.model,
        model.tokenizer,
        train_texts,
        max_len=cfg.MODEL.MAX_LEN,
        device=device,
        batch_size=cfg.MODEL.BATCH_SIZE,
    )
    probes = layer_probe_curve(
        train_reps.hidden, y_train, test_reps.hidden, y_test, seed=int(metrics["seed"])
    )
