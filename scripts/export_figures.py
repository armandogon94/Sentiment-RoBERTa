def _rebuilt_splits(cfg: Any, run_dir: Path) -> Any:
    """Rebuild the run's own splits and prove the test half matches ``predictions.parquet``.

    The probe needs TRAIN rows, and a run directory holds only the test rows. The split is a
    pure function of the config and the seed, so it is rebuilt here rather than stored twice.
    That reconstruction is only trustworthy if it reproduces the half that *was* stored, so
    the test texts are compared row for row before anything is fitted.
    """
    from datasets.splits import combined_text
    from train import build_splits

    if not Path(cfg.DATA.TRAIN_PATH).is_file():
        raise FileNotFoundError(
            f"{cfg.DATA.TRAIN_PATH} not found; the layer-probe figure is fitted on the run's "
            "TRAIN rows, which live in the source parquet. Run `make data`, or pass "
            "--skip-model-figures."
        )
    splits, _ = build_splits(cfg)
    stored = [str(t) for t in _example_texts(run_dir)["text"]]
    rebuilt = [str(t) for t in combined_text(splits.test)]
    if rebuilt != stored:
        raise ValueError(
            "the rebuilt test split does not match predictions.parquet, so the rebuilt train "
            "split cannot be trusted either; refusing to fit a probe on it"
        )
    return splits


