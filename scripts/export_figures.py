def _load_model_for_figures(run_dir: Path, metrics: dict[str, Any]) -> Any:
    """Rebuild the run's transformer and load its saved weights."""
    import torch

    from cfg.schema import load_config
    from models.registry import create_model
    from models.roberta import RobertaSentiment
    from utils.device import resolve_device

    cfg = load_config(REPO_ROOT / metrics["config_path"])
    device = resolve_device(cfg.RUNTIME.DEVICE)
    # Narrowed to the concrete type: the figures need the raw nn.Module and the tokenizer,
    # neither of which belongs on the model-comparison Protocol.
    model = cast(
        RobertaSentiment,
        create_model(
            "roberta",
            pretrained=cfg.MODEL.PRETRAINED,
            revision=cfg.MODEL.REVISION,
            num_labels=cfg.MODEL.NUM_LABELS,
            max_len=cfg.MODEL.MAX_LEN,
            batch_size=cfg.MODEL.BATCH_SIZE,
            epochs=cfg.MODEL.EPOCHS,
            lr=cfg.MODEL.LR,
            seed=cfg.SEED,
            device=device,
            random_weight_layers=cfg.MODEL.RANDOM_WEIGHT_LAYERS,
        ),
    )
    ckpt = run_dir / "model_roberta.pt"
    if not ckpt.exists():
        raise FileNotFoundError(
            f"{ckpt} not found; interpretability figures need the run's weights. "
            "Re-run train.py, or pass --skip-model-figures."
        )
    state = torch.load(ckpt, map_location=device, weights_only=True)
    model.model.load_state_dict(state)
    model.model.eval()
    return model, cfg, device


